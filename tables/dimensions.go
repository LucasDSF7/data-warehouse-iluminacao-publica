func DimDataTable(dbpool *pgxpool.Pool) {
	query := `CREATE TABLE IF NOT EXISTS dw.dim_data(
		data_key INT PRIMARY KEY,
		data DATE,
		dia_no_mes INT,
		dia_no_ano INT,
		nome_dia_semana VARCHAR(20),
		semana_do_ano INT,
		numero_mes INT,
		nome_mes VARCHAR(20),
		ano INT,
		trimestre INT,
		trimestre_ano VARCHAR(25),
		trimestre_contrato_aracaju VARCHAR(20)
	);
	COMMENT ON TABLE dw.dim_data IS 'Dimensão de datas do Data Warehouse.';
	COMMENT ON COLUMN dw.dim_data.trimestre_contrato_aracaju IS 'Indica o Trimestre do Contrato. O primeiro trimestre inicia em dez/2021 e é incrementado a cada três meses a partir do início do contrato.';

	WITH gen_datas AS (
			SELECT data::date FROM generate_series(
			'2021-06-01'::date,
			'2041-12-31'::date,
			'1 day'::interval
		) data
	)
	INSERT INTO dw.dim_data (data_key, data, dia_no_mes, dia_no_ano, nome_dia_semana,
		semana_do_ano, numero_mes, nome_mes, ano, trimestre, trimestre_ano, trimestre_contrato_aracaju)
	SELECT TO_CHAR(data, 'YYYYMMDD')::integer data_key,
	data,
	EXTRACT(DAY FROM data) dia_no_mes,
	EXTRACT(DOY FROM data) dia_no_ano,
	CASE
		WHEN EXTRACT(dow FROM data) = 0 THEN 'Domingo'
		WHEN EXTRACT(dow FROM data) = 1 THEN 'Segunda'
		WHEN EXTRACT(dow FROM data) = 2 THEN 'Terça'
		WHEN EXTRACT(dow FROM data) = 3 THEN 'Quarta'
		WHEN EXTRACT(dow FROM data) = 4 THEN 'Quinta'
		WHEN EXTRACT(dow FROM data) = 5 THEN 'Sexta'
		WHEN EXTRACT(dow FROM data) = 6 THEN 'Sábado'
	END AS nome_dia_semana,
	EXTRACT(WEEK FROM data) semana_do_ano,
	EXTRACT(MONTH FROM data) numero_mes,
	CASE
		WHEN EXTRACT(MONTH FROM data) = 1 THEN 'Janeiro'
		WHEN EXTRACT(MONTH FROM data) = 2 THEN 'Fevereiro'
		WHEN EXTRACT(MONTH FROM data) = 3 THEN 'Março'
		WHEN EXTRACT(MONTH FROM data) = 4 THEN 'Abril'
		WHEN EXTRACT(MONTH FROM data) = 5 THEN 'Maio'
		WHEN EXTRACT(MONTH FROM data) = 6 THEN 'Junho'
		WHEN EXTRACT(MONTH FROM data) = 7 THEN 'Julho'
		WHEN EXTRACT(MONTH FROM data) = 8 THEN 'Agosto'
		WHEN EXTRACT(MONTH FROM data) = 9 THEN 'Setembro'
		WHEN EXTRACT(MONTH FROM data) = 10 THEN 'Outubro'
		WHEN EXTRACT(MONTH FROM data) = 11 THEN 'Novembro'
		WHEN EXTRACT(MONTH FROM data) = 12 THEN 'Dezembro'
	END AS nome_mes,
	EXTRACT(YEAR FROM data) ano,
	EXTRACT(QUARTER FROM data) trimestre,
	EXTRACT(QUARTER FROM data)::text || 'º Trimestre de ' || EXTRACT(YEAR FROM data)::text trimestre_ano,
	CASE
		WHEN data < '2021-12-01'::date THEN 'T0'
		ELSE 'T' ||
	(EXTRACT(MONTH FROM data) -12 + (EXTRACT(YEAR FROM data) - 2021) * 12)::integer / 3 + 1
	END AS trimestre_contrato_aracaju
	FROM gen_datas
	ON CONFLICT (data_key) DO NOTHING;

	INSERT INTO dw.dim_data (data_key, data, dia_no_mes, dia_no_ano, nome_dia_semana,
		semana_do_ano, numero_mes, nome_mes, ano, trimestre, trimestre_ano, trimestre_contrato_aracaju)
	VALUES (
		-1, '0001-01-01'::date, 0, 0, 'Desconhecido', 0, 0, 'Desconhecido', 0, 0, 'Desconhecido', 'Desconhecido'
	)
	ON CONFLICT (data_key) DO NOTHING;
	`
	_, err := dbpool.Exec(context.Background(), query)
	if err != nil {
		fmt.Println(err)
	}
	RolePlayDataCriacao(dbpool)
	RolePlayDataIniciado(dbpool)
	RolePlayDataCancelado(dbpool)
	RolePlayDataConclusao(dbpool)
}

