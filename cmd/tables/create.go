package main

import (
	"context"
	"fmt"

	"github.com/LucasDSF7/data-warehouse-iluminacao-publica/postgres"
	"github.com/jackc/pgx/v5/pgxpool"
)

func dimPontoServicoTable(dbpool *pgxpool.Pool) {
	query := `CREATE TABLE IF NOT EXISTS dw.dim_ponto_servico(
		ponto_servico_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		id_ponto_servico INT,
		plaqueta VARCHAR(20) DEFAULT 'Não informado',
		endereco TEXT DEFAULT 'Não informado',
		latitude FLOAT,
		longitude FLOAT,
		cidade VARCHAR(20) NOT NULL,
		bairro VARCHAR(30) DEFAULT 'Não informado',
		logradouro_eixo TEXT DEFAULT 'Não informado',
		logradouro_google TEXT DEFAULT 'Não informado',
		documento_evento TEXT DEFAULT 'Não preenchido',
		e_condominio VARCHAR(20) DEFAULT 'Não',
		e_banco_credito VARCHAR(20) DEFAULT 'Não',
		e_ponto_escuro VARCHAR(20) DEFAULT 'Não',
		valor_creditos DECIMAL(5,2) DEFAULT 0.00,
		e_exclusividade_ip VARCHAR(20) DEFAULT 'Não',
		altura_poste DECIMAL(4,1) DEFAULT 0.0,
		tipo_altura_poste VARCHAR(20) DEFAULT 'Baixo',
		tipo_poste VARCHAR(50) DEFAULT 'Não informado',
		e_telegestao VARCHAR(20) DEFAULT 'Não',
		marco_telegestao VARCHAR(20) DEFAULT 'Sem telegestão',
		largura_via_veiculos DECIMAL(4,1) DEFAULT 0.0,
		largura_via_pedestres DECIMAL(4,1) DEFAULT 0.0,
		distancia_entre_postes DECIMAL(4,1) DEFAULT 0.0,
		classificacao_via_veiculos VARCHAR(20) DEFAULT 'Não se aplica',
		classificacao_via_pedestres VARCHAR(20) DEFAULT 'Não se aplica',
		idcomando VARCHAR(20) DEFAULT 'Não preenchido',
		data_modificacao DATE DEFAULT CURRENT_DATE
	);
	COMMENT ON COLUMN dw.dim_ponto_servico.ponto_servico_key IS 'Chave surrogate (PK) da dimensão de ponto de serviço';
	COMMENT ON COLUMN dw.dim_ponto_servico.id_ponto_servico IS 'Super chave natural do sistema operacional. Indica um ponto de serviço, que constitui de poste, suporte e luminárias de iluminação pública';
	COMMENT ON COLUMN dw.dim_ponto_servico.plaqueta IS 'Plaqueta de identificação física localizada no poste (Ponto de Serviço)';
	COMMENT ON COLUMN dw.dim_ponto_servico.endereco IS 'Endereço do ponto de serviço';
	COMMENT ON COLUMN dw.dim_ponto_servico.latitude IS 'A latitude em graus decimais do ponto de serviço.';
	COMMENT ON COLUMN dw.dim_ponto_servico.longitude IS 'A longitude em graus decimais do ponto de serviço.';
	COMMENT ON COLUMN dw.dim_ponto_servico.cidade IS 'Cidade da concessão da iluminação pública do ponto de serviço';
	COMMENT ON COLUMN dw.dim_ponto_servico.bairro IS 'Bairro onde está localizado o ponto de serviço';
	COMMENT ON COLUMN dw.dim_ponto_servico.logradouro_eixo IS 'Nome do logradouro registrado na prefeitura da Cidade da concessão do ponto de serviço';
	COMMENT ON COLUMN dw.dim_ponto_servico.logradouro_google IS 'Nome do logradouro registrado no Google Maps da Cidade da concessão do ponto de serviço';
	COMMENT ON COLUMN dw.dim_ponto_servico.documento_evento IS 'Informa uma observação importante relacionada ao ponto de serviço. Geralmente informa um número de Ofício da Prefeitura/Umurb para extensão do parque de iluminação pública';
	COMMENT ON COLUMN dw.dim_ponto_servico.e_condominio IS 'Sim ou Não. Informa se o ponto de serviço está em um condomínio.';
	COMMENT ON COLUMN dw.dim_ponto_servico.e_banco_credito IS 'Sim ou Não. Informa se o ponto de serviço foi instalado através de Banco de Crédito. Mecanismo do contrato de concessão com a Prefeitura/EMURB para extensão do parque de iluminação pública com cobrança de créditos do banco de créditos';
	COMMENT ON COLUMN dw.dim_ponto_servico.e_ponto_escuro IS 'Sim ou Não. Informa se o ponto de serviço foi instalado através de Ponto Escuro. Mecanismo do contrato de concessão com a Prefeitura/EMURB para extensão do parque de iluminação pública sem cobrança de créditos do banco de créditos.';
	COMMENT ON COLUMN dw.dim_ponto_servico.valor_creditos IS 'Valor dos créditos gastos para ampliação do parque de iluminação pública da concessão';
	COMMENT ON COLUMN dw.dim_ponto_servico.e_exclusividade_ip IS 'Se o ponto de serviço é de exclusivadade IP ou não. Um ponto exclusivo deve possuir medição de energia em um comando elétrico';
	COMMENT ON COLUMN dw.dim_ponto_servico.altura_poste IS 'Valor da altura do poste do ponto de serviço. A altura é total, sendo necessário avaliar se o poste está engastado para achar a altura útil da luminária instalada';
	COMMENT ON COLUMN dw.dim_ponto_servico.tipo_altura_poste IS 'Alto ou Baixo. Faz referência se é necessário alugar caminhão munck ou equivalente para alcançar as luminárias do ponto de serviço. Se a altura útil for superior a 10 metros, deve ser necessário um caminhão munck, ou seja, o tipo_altura_poste seria "Alto" nesse caso';
	COMMENT ON COLUMN dw.dim_ponto_servico.tipo_poste IS 'O tipo do poste do ponto de serviço. Pode ser "Concreto circular", "Aço reto", entre outros.';
	COMMENT ON COLUMN dw.dim_ponto_servico.e_telegestao IS 'Se o ponto de serviço possui sistema de telegestão ou não';
	COMMENT ON COLUMN dw.dim_ponto_servico.marco_telegestao IS 'Informa em qual Marco do contrato foi instalado Telegestão no ponto de serviço.';
	COMMENT ON COLUMN dw.dim_ponto_servico.largura_via_veiculos IS 'Informa a largura da via de veículos em que o ponto de serviço está instalado.';
	COMMENT ON COLUMN dw.dim_ponto_servico.largura_via_pedestres IS 'Informa a largura da calçada em que o ponto de serviço está instalado.';
	COMMENT ON COLUMN dw.dim_ponto_servico.distancia_entre_postes IS 'Informa a distância entre os pontos de serviços em uma mesma via.';
	COMMENT ON COLUMN dw.dim_ponto_servico.classificacao_via_veiculos IS 'Informa a classificação da via de veículos, segundo a NBR 5101 e o anexo do contrato de concessão.';
	COMMENT ON COLUMN dw.dim_ponto_servico.classificacao_via_pedestres IS 'Informa a classificação da via de pedestres, segundo a NBR 5101 e o anexo do contrato de concessão.';
	COMMENT ON COLUMN dw.dim_ponto_servico.idcomando IS 'Informa qual o id do comando em que o ponto de serviço está instalado. Caso o valor seja 0, desconsiderar a existência de comando para esse ponto de serviço.';
	COMMENT ON COLUMN dw.dim_ponto_servico.data_modificacao IS 'Data em que foi inserido ou atualizado informação na linha.';
	COMMENT ON TABLE dw.dim_ponto_servico IS 'Dimensão SCD Type 1 de pontos de serviços da concessão de iluminação pública. Essa dimensão é Type 1, pois é a forma mais natural de tratar dados para a gerência. Quando, por exemplo, uma plaqueta muda de valor, todos os registros antigos do mesmo ponto de serviço devem acompanhar a mudança.';
	CREATE INDEX idx_dim_id_ponto_servico ON dw.dim_ponto_servico (id_ponto_servico);
	`
	_, err := dbpool.Exec(context.Background(), query)
	if err != nil {
		fmt.Println(err)
	}
}

func main() {
	dbpool := postgres.GetDriverConecta()
	defer dbpool.Close()
	dimPontoServicoTable(dbpool)
}
